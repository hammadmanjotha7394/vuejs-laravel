<?php

namespace App\Mail;

use Illuminate\Bus\Queueable;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;

class TestMail extends Mailable
{
    use Queueable, SerializesModels;

    public function __construct(
        public string $siteName,
        public string $sentAt
    ) {}

    public function envelope(): Envelope
    {
        return new Envelope(
            subject: "SMTP Verification Test: {$this->siteName}",
        );
    }

    public function content(): Content
    {
        return new Content(
            htmlString: <<<HTML
            <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; max-width: 580px; margin: 0 auto; padding: 32px 24px; color: #1f2937; line-height: 1.6;">
                <div style="padding-bottom: 20px; border-bottom: 1px solid #e5e7eb;">
                    <h2 style="color: #2F5D50; margin: 0; font-size: 20px;">{$this->siteName} · Mail System Test</h2>
                </div>
                <div style="padding: 24px 0;">
                    <p style="margin: 0 0 16px;">Hello,</p>
                    <p style="margin: 0 0 16px;">This email confirms that your outgoing SMTP credentials (Hostinger SMTP or custom mail server) and sender configurations are connected and working properly.</p>
                    <div style="background-color: #f3f4f6; border-radius: 8px; padding: 16px; font-size: 13px; color: #4b5563;">
                        <strong>Dispatch Timestamp:</strong> {$this->sentAt}<br>
                        <strong>Application Status:</strong> Online & Active
                    </div>
                </div>
                <div style="padding-top: 16px; border-top: 1px solid #e5e7eb; font-size: 12px; color: #9ca3af;">
                    Automated system message generated by {$this->siteName} Admin Panel.
                </div>
            </div>
            HTML
        );
    }
}
